def zi(v):
    v = round(v)
    return 0 if v <= 24 else 1 if v <= 44 else 2 if v <= 54 else 3 if v <= 74 else 4


def chg(xs):
    return [b - a for a, b in zip(xs, xs[1:])]


def reversals(xs):
    c = chg(xs)
    return sum(1 for a, b in zip(c, c[1:]) if a * b < 0)


def switches(xs):
    z = [zi(v) for v in xs]
    return sum(1 for a, b in zip(z, z[1:]) if a != b)


